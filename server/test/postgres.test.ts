describe('SQL translation for Postgres', () => {
  it('numbers ? placeholders in order and leaves strings, quoted names and comments alone', () => {
    const s = translateSql(`SELECT 'what? it''s ?' AS "a?", x FROM t -- why?\nWHERE a = ? AND b IN (?, ?) /* ? */ AND c = '?'`);
    expect(s.text).toBe(`SELECT 'what? it''s ?' AS "a?", x FROM t -- why?\nWHERE a = $1 AND b IN ($2, $3) /* ? */ AND c = '?'`);
    expect(bindValues(s, ['x', 1, 2])).toEqual(['x', 1, 2]);
  });

  it('gives a named param used twice one number, with or without the $ in the key', () => {
    const s = translateSql('UPDATE t SET a = $v, b = $w WHERE c = $v AND d = :w');
    expect(s.text).toBe('UPDATE t SET a = $1, b = $2 WHERE c = $1 AND d = $2');
    expect(bindValues(s, { v: 5, w: null })).toEqual([5, null]);
    expect(bindValues(s, { $v: 'x', w: true } as any)).toEqual(['x', 1]);
  });

  it('makes LIKE case-insensitive like SQLite but keeps casts and string contents', () => {
    expect(translateSql("SELECT x::text FROM t WHERE a LIKE ? ESCAPE '\\' AND b NOT like 'LIKE'").text).toBe("SELECT x::text FROM t WHERE a ILIKE $1 ESCAPE '\\' AND b NOT ILIKE 'LIKE'");
    expect(translateSql('SELECT 1 FROM t WHERE a ILIKE ?').text).toBe('SELECT 1 FROM t WHERE a ILIKE $1');
  });

  it('maps ids to identity columns, INTEGER to BIGINT, REAL to DOUBLE PRECISION', () => {
    const ddl = translateDdl(`CREATE TABLE t (
      id INTEGER PRIMARY KEY,
      ws INTEGER NOT NULL REFERENCES w(id), -- an INTEGER note
      score REAL,
      name TEXT NOT NULL DEFAULT 'INTEGER'
    );
    CREATE UNIQUE INDEX t_name ON t(name) WHERE ws IS NOT NULL;`);
    expect(ddl).toContain('id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
    expect(ddl).toContain('ws BIGINT NOT NULL REFERENCES w(id)');
    expect(ddl).toContain('score DOUBLE PRECISION');
    expect(ddl).toContain("DEFAULT 'INTEGER'");
    expect(ddl).toContain('CREATE UNIQUE INDEX t_name ON t(name) WHERE ws IS NOT NULL;');
    expect(ddl).not.toContain('an INTEGER note');
  });

  it('turns a case-insensitive unique column into a unique index on lower()', () => {
    const ddl = translateDdl('CREATE TABLE users (\n id INTEGER PRIMARY KEY,\n email TEXT NOT NULL UNIQUE COLLATE NOCASE,\n name TEXT\n);');
    expect(ddl).toContain('email TEXT NOT NULL,');
    expect(ddl).not.toMatch(/NOCASE|UNIQUE,/);
    expect(ddl).toContain('CREATE UNIQUE INDEX users_email_lower ON users (lower(email));');
  });

  it('translates every migration, including the table rebuilds, to plain Postgres types', () => {
    for (const sql of MIGRATIONS) {
      const ddl = translateDdl(sql);
      expect(ddl).not.toMatch(/\bINTEGER\b|\bREAL\b|NOCASE|PRAGMA/);
    }
    const rebuild = translateDdl(MIGRATIONS[1]);
    expect(rebuild).toContain('ALTER TABLE conversations_new RENAME TO conversations;');
    expect(rebuild).toContain("WHERE dedupe_key IS NOT NULL AND status IN ('queued', 'running')");
  });
});

describe('choosing the database', () => {
  it('stays on SQLite without DATABASE_URL and refuses a URL that is not Postgres', () => {
    const db = openDatabase({ dbPath: ':memory:', databaseUrl: undefined });
    expect(db.dialect).toBe('sqlite');
    db.close();
    expect(() => loadConfig({ DATA_DIR: join(tmpdir(), 'openreach-test'), APP_SECRET: 'x', DATABASE_URL: 'mysql://localhost/x' })).toThrow(/postgres:\/\//);
    expect(loadConfig({ DATA_DIR: join(tmpdir(), 'openreach-test'), APP_SECRET: 'x', DATABASE_URL: 'postgres://u:p@db:5432/openreach' }).databaseUrl).toBe('postgres://u:p@db:5432/openreach');
  });

  it('always makes the SQLite instance the leader', () => {
    const db = new DB(':memory:');
    const seen: string[] = [];
    const lead = new Leadership(db, { onLead: () => seen.push('lead'), onLose: () => seen.push('lose') });
    lead.check();
    lead.check();
    expect(seen).toEqual(['lead']);
    expect(lead.isLeader).toBe(true);
    db.close();
  });
});

describe.skipIf(!TEST_PG_URL)('Postgres backend', () => {
  it('returns new ids, 0 for tables without an id, numbers for counts and 0/1 for booleans', () => {
    const db = testDb();
    expect(db.dialect).toBe('postgres');
    const ws = db.insert('workspaces', { name: 'A', created_at: 1 });
    const user = db.insert('users', { workspace_id: ws, email: 'a@example.com', name: 'A', password_hash: 'x', created_at: 1 });
    expect(ws).toBeGreaterThan(0);
    expect(user).toBeGreaterThan(0);
    expect(db.insert('sessions', { token: 't1', user_id: user, expires_at: 2 ** 41 })).toBe(0);
    expect(db.insert('memberships', { user_id: user, workspace_id: ws, role: 'owner', created_at: 1 })).toBe(0);
    expect(db.get('SELECT COUNT(*) AS n, SUM(expires_at) AS s, 1 = 1 AS yes FROM sessions')).toEqual({ n: 1, s: 2 ** 41, yes: 1 });
    // users.email was UNIQUE COLLATE NOCASE on SQLite.
    expect(() => db.insert('users', { workspace_id: ws, email: 'A@Example.com', name: 'B', password_hash: 'x', created_at: 1 })).toThrow(/users_email_lower/);
    expect(db.get('SELECT id FROM users WHERE lower(email) = lower(?)', ['A@EXAMPLE.COM'])).toEqual({ id: user });
    expect(db.all("SELECT name FROM workspaces WHERE name LIKE 'a%'")).toEqual([{ name: 'A' }]);
  });

  it('joins nested transactions, rolls back on errors and runs afterCommit only after a commit', () => {
    const db = testDb();
    const done: string[] = [];
    db.tx(() => {
      db.insert('workspaces', { name: 'kept', created_at: 1 });
      db.tx(() => db.insert('workspaces', { name: 'inner', created_at: 1 }));
      db.afterCommit(() => done.push('first'));
    });
    expect(() =>
      db.tx(() => {
        db.insert('workspaces', { name: 'undone', created_at: 1 });
        db.afterCommit(() => done.push('second'));
        throw new Error('boom');
      }),
    ).toThrow('boom');
    expect(db.all<{ name: string }>('SELECT name FROM workspaces ORDER BY id').map((r) => r.name)).toEqual(['kept', 'inner']);
    expect(done).toEqual(['first']);
    // The connection is usable after a failed statement outside a transaction.
    expect(() => db.run('INSERT INTO nope VALUES (1)')).toThrow();
    expect(db.get('SELECT COUNT(*) AS n FROM workspaces')).toEqual({ n: 2 });
  });

  it('runs migrations once and records them', () => {
    const schema = testSchema();
    const db = openPg({ schema, createSchema: true, dropSchemaOnClose: true });
    expect(db.get('SELECT COUNT(*) AS n FROM migrations')).toEqual({ n: MIGRATIONS.length });
    db.migrate();
    const again = openPg({ schema });
    expect(again.get('SELECT COUNT(*) AS n FROM migrations')).toEqual({ n: MIGRATIONS.length });
  });

  it('lets only one connection hold the leader lock, and hands it over when that connection ends', () => {
    const key = 1_000_000 + Math.floor(Math.random() * 1_000_000);
    const schema = testSchema();
    const a = openPg({ schema, createSchema: true, dropSchemaOnClose: true });
    const b = openPg({ schema, migrate: false });
    const seen: string[] = [];
    const leadA = new Leadership(a, { onLead: () => seen.push('a:lead'), onLose: () => seen.push('a:lose') }, key);
    const leadB = new Leadership(b, { onLead: () => seen.push('b:lead'), onLose: () => seen.push('b:lose') }, key);
    leadA.check();
    leadB.check();
    leadA.check();
    expect(seen).toEqual(['a:lead']);
    expect(leadA.isLeader).toBe(true);
    expect(leadB.isLeader).toBe(false);
    a.close();
    leadB.check();
    expect(seen).toEqual(['a:lead', 'b:lead']);
  });

  it('demotes the leader when its connection is lost, then takes the lock again on the new one', async () => {
    const key = 2_000_000 + Math.floor(Math.random() * 1_000_000);
    const schema = testSchema();
    const a = openPg({ schema, createSchema: true, dropSchemaOnClose: true });
    const killer = openPg({ schema, migrate: false });
    const seen: string[] = [];
    const lead = new Leadership(a, { onLead: () => seen.push('lead'), onLose: () => seen.push('lose') }, key);
    lead.check();
    const pid = a.get<{ pid: number }>('SELECT pg_backend_pid() AS pid')!.pid;
    killer.get('SELECT pg_terminate_backend(CAST(? AS INTEGER))', [pid]);
    // The worker notices the dropped socket on its own event loop; a check on the dead socket fails and is retried.
    for (let i = 0; i < 20 && !seen.includes('lose'); i++) {
      await new Promise((r) => setTimeout(r, 50));
      lead.check();
    }
    expect(seen).toEqual(['lead', 'lose', 'lead']);
    expect(lead.isLeader).toBe(true);
  });

  it('never lets two workers claim the same job: a locked job is skipped, not waited for', () => {
    const schema = testSchema();
    const a = openPg({ schema, createSchema: true, dropSchemaOnClose: true });
    const b = openPg({ schema, migrate: false });
    const clock = new ManualClock(MONDAY_8AM);
    const ctxA = buildContext(testConfig(), clock, { db: a });
    const ctxB = buildContext(testConfig(), clock, { db: b });
    const ws = a.insert('workspaces', { name: 'W', created_at: clock.now() });
    const first = ctxA.jobs.enqueue('ai.classify', { messageId: 1 } as any, { workspaceId: ws });
    const second = ctxA.jobs.enqueue('ai.classify', { messageId: 2 } as any, { workspaceId: ws });
    const claim = (ctx: typeof ctxA) => (ctx.jobs as any).claim(['ai.classify'], clock.now()) as { id: number } | undefined;
    a.tx(() => {
      // A's claim keeps its row locked until this transaction ends; B must move on to the next job.
      expect(claim(ctxA)?.id).toBe(first);
      expect(claim(ctxB)?.id).toBe(second);
      expect(claim(ctxB)).toBeUndefined();
    });
    expect(b.all('SELECT id, status, attempts FROM jobs ORDER BY id')).toEqual([
      { id: first, status: 'running', attempts: 1 },
      { id: second, status: 'running', attempts: 1 },
    ]);
  });

  it('leaves a job another instance is still running to it until its lease ends, and keeps that run’s result', async () => {
    const schema = testSchema();
    const a = openPg({ schema, createSchema: true, dropSchemaOnClose: true });
    const b = openPg({ schema, migrate: false });
    const clock = new ManualClock(MONDAY_8AM);
    const ctxA = buildContext(testConfig(), clock, { db: a });
    const ctxB = buildContext(testConfig(), clock, { db: b });
    const ws = a.insert('workspaces', { name: 'W', created_at: clock.now() });
    let finish!: () => void;
    ctxA.jobs.register('ai.classify', () => new Promise<void>((r) => (finish = r)));
    let ranOnB = 0;
    ctxB.jobs.register('ai.classify', async () => void ranOnB++);
    const id = ctxA.jobs.enqueue('ai.classify', { messageId: 1 }, { workspaceId: ws });
    const running = ctxA.jobs.tick();
    await new Promise((r) => setTimeout(r, 0));
    // B becomes the leader while A (which lost its lock) is still running the job: B's first tick leaves it.
    await ctxB.jobs.tick();
    expect(ranOnB).toBe(0);
    expect(b.get('SELECT status, attempts FROM jobs WHERE id = ?', [id])).toEqual({ status: 'running', attempts: 1 });
    finish();
    await running;
    expect(b.get('SELECT status FROM jobs WHERE id = ?', [id])).toEqual({ status: 'done' });
  });

  it('makes plan-limited inserts of one billing root take turns (transaction advisory lock)', () => {
    const schema = testSchema();
    const a = openPg({ schema, createSchema: true, dropSchemaOnClose: true });
    const b = openPg({ schema, migrate: false });
    const ctx = buildContext(testConfig(), new ManualClock(MONDAY_8AM), { db: a, stripe: null });
    const ws = a.insert('workspaces', { name: 'W', created_at: 1 });
    // The lock's 64-bit key shows in pg_locks as classid (high half) and objid (low half).
    const held = () => b.get<{ n: number }>("SELECT COUNT(*) AS n FROM pg_locks WHERE locktype = 'advisory' AND granted AND CAST(classid AS BIGINT) = 20556 AND CAST(objid AS BIGINT) = CAST(? AS BIGINT)", [ws])!.n;
    // Billing off: nothing is limited, so nothing to lock.
    withPlanLock(ctx, ws, () => expect(held()).toBe(0));
    ctx.stripe = {} as any;
    withPlanLock(ctx, ws, () => {
      expect(held()).toBe(1);
      // Another instance's check would wait here; its try-variant says the lock is taken.
      b.tx(() => expect(b.get('SELECT pg_try_advisory_xact_lock(CAST(? AS BIGINT)) AS ok', [0x504c * 2 ** 32 + ws])).toEqual({ ok: 0 }));
    });
    expect(held()).toBe(0); // released with the transaction
    expect(() => a.txLock(1)).toThrow(/needs a transaction/);
  });

  it('fails a call that takes too long instead of hanging, and keeps working afterwards', () => {
    const schema = testSchema();
    openPg({ schema, createSchema: true, dropSchemaOnClose: true });
    const a = openPg({ schema, migrate: false, callTimeoutMs: 300 });
    expect(a).toBeInstanceOf(PgDatabase);
    expect(() => a.get('SELECT pg_sleep(3) AS x')).toThrow(/timed out/);
    // A new worker and connection replace the stuck one.
    expect(a.get('SELECT COUNT(*) AS n FROM migrations')).toEqual({ n: MIGRATIONS.length });
  });
});
