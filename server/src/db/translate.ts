// Turns the portable SQLite dialect the app is written in (PREMIUM_PLAN.md 2.2) into Postgres SQL.
// Only runs when DATABASE_URL points at Postgres; SQLite statements are never touched.

export interface PgStatement {
  text: string;
  // Where each $n comes from: an index into positional params, or the name of a named param.
  slots: (number | string)[];
}

type Chunk = { code: boolean; text: string };

// Splits SQL into code and the parts that must be left alone: string literals, quoted identifiers, comments.
function chunks(sql: string): Chunk[] {
  const out: Chunk[] = [];
  let code = '';
  let i = 0;
  const flush = () => {
    if (code) out.push({ code: true, text: code });
    code = '';
  };
  while (i < sql.length) {
    const c = sql[i];
    let end = -1;
    if (c === "'" || c === '"') {
      // '' (or "") inside the quotes is an escaped quote.
      end = i + 1;
      for (;;) {
        const j = sql.indexOf(c, end);
        if (j < 0) {
          end = sql.length;
          break;
        }
        if (sql[j + 1] === c) end = j + 2;
        else {
          end = j + 1;
          break;
        }
      }
    } else if (c === '-' && sql[i + 1] === '-') {
      const j = sql.indexOf('\n', i);
      end = j < 0 ? sql.length : j;
    } else if (c === '/' && sql[i + 1] === '*') {
      const j = sql.indexOf('*/', i + 2);
      end = j < 0 ? sql.length : j + 2;
    }
    if (end < 0) {
      code += c;
      i++;
      continue;
    }
    flush();
    out.push({ code: false, text: sql.slice(i, end) });
    i = end;
  }
  flush();
  return out;
}

const cache = new Map<string, PgStatement>();
const CACHE_MAX = 5000;

// `?` and `$name`/`:name`/`@name` become $1..$n (a name used twice keeps one number); LIKE becomes ILIKE,
// since the app's LIKE searches expect SQLite's case-insensitive matching.
export function translateSql(sql: string): PgStatement {
  const hit = cache.get(sql);
  if (hit) return hit;
  const slots: (number | string)[] = [];
  const named = new Map<string, number>();
  let positional = 0;
  const text = chunks(sql)
    .map((ch) => {
      if (!ch.code) return ch.text;
      return ch.text.replace(/(::)|\?|([$:@])([A-Za-z_][A-Za-z0-9_]*)|\b(I?LIKE)\b/gi, (m, cast, prefix, name, like) => {
        if (cast) return m;
        if (like) return 'ILIKE';
        if (m === '?') {
          slots.push(positional++);
          return '$' + slots.length;
        }
        let n = named.get(name);
        if (n === undefined) {
          slots.push(name);
          n = slots.length;
          named.set(name, n);
        }
        return '$' + n;
      });
    })
    .join('');
  const stmt = { text, slots };
  if (cache.size >= CACHE_MAX) cache.clear();
  cache.set(sql, stmt);
  return stmt;
}

// Positional or named params (node:sqlite style: keys without the prefix) in $n order, as pg sends them.
export function bindValues(stmt: PgStatement, params: Record<string, unknown> | unknown[]): unknown[] {
  return stmt.slots.map((slot) => {
    const v = Array.isArray(params) ? params[slot as number] : typeof slot === 'string' ? (slot in params ? params[slot] : params['$' + slot]) : undefined;
    return pgValue(v);
  });
}

function pgValue(v: unknown) {
  if (v === undefined || v === null) return null;
  if (typeof v === 'boolean') return v ? 1 : 0;
  if (typeof v === 'bigint') return v.toString();
  if (v instanceof Uint8Array && !Buffer.isBuffer(v)) return Buffer.from(v.buffer, v.byteOffset, v.byteLength);
  return v;
}

// Migration DDL for Postgres: ids become identity columns, INTEGER becomes BIGINT (millisecond times
// overflow 32 bits), REAL becomes DOUBLE PRECISION, and a case-insensitive UNIQUE column becomes a unique
// index on lower(column). Data statements in old migrations pass through (they are no-ops on a new database).
export function translateDdl(sql: string): string {
  const extra: string[] = [];
  const parts = chunks(sql).map((ch) => (ch.code ? ch : { code: false, text: ch.text.startsWith('--') || ch.text.startsWith('/*') ? '' : ch.text }));
  let table = '';
  const text = parts
    .map((ch) => {
      if (!ch.code) return ch.text;
      return ch.text
        .replace(/\bPRAGMA\b[^;]*;?/gi, '')
        .replace(/\bCREATE TABLE (?:IF NOT EXISTS )?(\w+)|\b(\w+)(\s+TEXT(?:\s+NOT NULL)?)\s+UNIQUE\s+COLLATE\s+NOCASE\b|\s+COLLATE\s+NOCASE\b/gi, (m, created, col, type) => {
          if (created) {
            table = created;
            return m;
          }
          if (col) {
            extra.push(`CREATE UNIQUE INDEX ${table}_${col}_lower ON ${table} (lower(${col}));`);
            return col + type;
          }
          // A plain NOCASE column: comparisons on it must use lower() (rule 7).
          return '';
        })
        .replace(/\bid\s+INTEGER\s+PRIMARY\s+KEY\b/gi, 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
        .replace(/\bINTEGER\b/gi, 'BIGINT')
        .replace(/\bREAL\b/gi, 'DOUBLE PRECISION');
    })
    .join('');
  return extra.length ? `${text}\n${extra.join('\n')}\n` : text;
}
